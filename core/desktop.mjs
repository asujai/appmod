// The one-click layer: desktop shortcuts that start a recipe, a yes/no dialog when the app is
// already running without the recipe, and quitting that running copy. Windows, macOS, Linux.
import { execFileSync, spawnSync } from 'node:child_process'
import { mkdirSync, writeFileSync, existsSync, chmodSync, rmSync } from 'node:fs'
import { join, basename } from 'node:path'
import { homedir } from 'node:os'
import { projectRoot } from './recipe.mjs'
import { isRunning } from './launcher.mjs'

const sleep = ms => new Promise(resolve => setTimeout(resolve, ms))
const cli = join(projectRoot, 'bin', 'appmod.mjs')

// Shortcut names become file names: keep letters (any script), digits, spaces and ()-_.,
export const safeName = name => name.replace(/[\\/:*?"<>|]+/g, ' ').replace(/\s+/g, ' ').trim() || 'appmod'

// Windows: a .vbs wrapper starts node without a console window; the .lnk points at it.
export function windowsLauncher(recipe, node = process.execPath) {
  const q = s => s.replace(/"/g, '""')
  return (
    `' Generated by appmod: starts ${q(recipe.name)} with recipe ${recipe.id}\r\n` +
    `CreateObject("WScript.Shell").Run """${q(node)}"" ""${q(cli)}"" launch ""${q(recipe.root)}"" --gui", 0, False\r\n`
  )
}

// Linux: a freedesktop entry. Exec quoting follows the Desktop Entry spec.
export function linuxDesktopEntry(recipe, name, node = process.execPath) {
  const q = s => `"${s.replace(/(["`$\\])/g, '\\$1')}"`
  return ['[Desktop Entry]', 'Type=Application', `Name=${name}`, `Comment=${recipe.name} with appmod recipe ${recipe.id}`, `Exec=${q(node)} ${q(cli)} launch ${q(recipe.root)} --gui`, 'Terminal=false', 'Categories=Utility;', ''].join('\n')
}

// macOS: an AppleScript applet (osacompile ships with macOS) runs the launcher in the
// background, so no Terminal window stays open.
export function macShellCommand(recipe, node = process.execPath) {
  const sh = s => `'${s.replace(/'/g, `'\\''`)}'`
  return `nohup ${sh(node)} ${sh(cli)} launch ${sh(recipe.root)} --gui >/dev/null 2>&1 &`
}
export const macAppleScript = (recipe, node) => `do shell script "${macShellCommand(recipe, node).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`

function desktopDir() {
  if (process.platform === 'win32') {
    // UTF-8 output: desktop paths often contain non-ASCII names ("OneDrive\Masaüstü").
    const ps = "[Console]::OutputEncoding = [Text.Encoding]::UTF8; [Environment]::GetFolderPath('Desktop')"
    return execFileSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', ps], { encoding: 'utf8', windowsHide: true }).trim()
  }
  if (process.platform === 'linux') {
    const xdg = spawnSync('xdg-user-dir', ['DESKTOP'], { encoding: 'utf8' })
    if (xdg.status === 0 && xdg.stdout.trim()) return xdg.stdout.trim()
  }
  return join(homedir(), 'Desktop')
}

// Creates the shortcut and returns the paths written. `icon` is an exe whose icon to show.
export function createShortcut(recipe, { name, icon }) {
  const file = safeName(name)
  const desktop = desktopDir()
  if (process.platform === 'win32') {
    const dir = join(process.env.LOCALAPPDATA || homedir(), 'appmod')
    mkdirSync(dir, { recursive: true })
    const vbs = join(dir, `launch-${recipe.id}.vbs`)
    // Windows Script Host reads UTF-16 with a BOM as Unicode, anything else in the ANSI code
    // page, which would break paths with non-ASCII user names.
    writeFileSync(vbs, Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(windowsLauncher(recipe), 'utf16le')]))
    const ps = `$s=(New-Object -ComObject WScript.Shell).CreateShortcut($env:APPMOD_LNK);$s.TargetPath='wscript.exe';$s.Arguments='"'+$env:APPMOD_VBS+'"';if($env:APPMOD_ICON){$s.IconLocation=$env:APPMOD_ICON+',0'};$s.Description='appmod: '+$env:APPMOD_ID;$s.Save()`
    const lnk = join(desktop, `${file}.lnk`)
    execFileSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', ps], {
      windowsHide: true,
      env: { ...process.env, APPMOD_LNK: lnk, APPMOD_VBS: vbs, APPMOD_ICON: icon && existsSync(icon) ? icon : '', APPMOD_ID: recipe.id },
    })
    return [lnk, vbs]
  }
  if (process.platform === 'darwin') {
    const app = join(desktop, `${file}.app`)
    rmSync(app, { recursive: true, force: true })
    const res = spawnSync('osacompile', ['-o', app, '-e', macAppleScript(recipe)], { encoding: 'utf8' })
    if (res.status === 0) return [app]
    // Fallback: a .command file opens Terminal briefly but works everywhere.
    const command = join(desktop, `${file}.command`)
    writeFileSync(command, `#!/bin/sh\n${macShellCommand(recipe)}\n`)
    chmodSync(command, 0o755)
    return [command]
  }
  const entry = linuxDesktopEntry(recipe, name)
  const apps = join(process.env.XDG_DATA_HOME || join(homedir(), '.local', 'share'), 'applications')
  mkdirSync(apps, { recursive: true })
  const written = [join(apps, `appmod-${recipe.id}.desktop`)]
  if (existsSync(desktop)) written.push(join(desktop, `appmod-${recipe.id}.desktop`))
  for (const f of written) {
    writeFileSync(f, entry)
    chmodSync(f, 0o755)
  }
  return written
}

// A native yes/no question: true, false, or null when no dialog tool is available.
export function askYesNo(title, message) {
  const env = { ...process.env, APPMOD_TITLE: title, APPMOD_MSG: message }
  if (process.platform === 'win32') {
    const ps = "Add-Type -AssemblyName PresentationFramework; [System.Windows.MessageBox]::Show($env:APPMOD_MSG, $env:APPMOD_TITLE, 'YesNo', 'Question')"
    const res = spawnSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', ps], { encoding: 'utf8', env, windowsHide: true })
    if (res.error) return null
    return res.stdout.trim() === 'Yes'
  }
  if (process.platform === 'darwin') {
    const script = 'display dialog (system attribute "APPMOD_MSG") with title (system attribute "APPMOD_TITLE") buttons {"Cancel", "Restart"} default button "Restart"'
    const res = spawnSync('osascript', ['-e', script], { env })
    return res.error ? null : res.status === 0
  }
  for (const [cmd, args] of [['zenity', ['--question', '--title', title, '--text', message]], ['kdialog', ['--title', title, '--yesno', message]]]) {
    const res = spawnSync(cmd, args, { env })
    if (!res.error) return res.status === 0
  }
  return null
}

// A notice the user sees when the launcher runs without a console (from a shortcut).
export function notify(title, message) {
  const env = { ...process.env, APPMOD_TITLE: title, APPMOD_MSG: message }
  if (process.platform === 'win32') {
    spawnSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', "Add-Type -AssemblyName PresentationFramework; [void][System.Windows.MessageBox]::Show($env:APPMOD_MSG, $env:APPMOD_TITLE, 'OK', 'Warning')"], { env, windowsHide: true })
  } else if (process.platform === 'darwin') {
    spawnSync('osascript', ['-e', 'display alert (system attribute "APPMOD_TITLE") message (system attribute "APPMOD_MSG")'], { env })
  } else {
    const res = spawnSync('zenity', ['--warning', '--title', title, '--text', message], { env })
    if (res.error) spawnSync('notify-send', [title, message], { env })
  }
}

// Quits a running app: politely first (windows get a close request), then forcefully after
// timeoutMs. Only called after the user agreed (dialog or --restart).
export async function stopApp(exeName, { timeoutMs = 6000 } = {}) {
  const polite = process.platform === 'win32' ? ['taskkill', ['/IM', exeName, '/T']] : ['pkill', ['-TERM', '-x', basename(exeName)]]
  const force = process.platform === 'win32' ? ['taskkill', ['/IM', exeName, '/T', '/F']] : ['pkill', ['-KILL', '-x', basename(exeName)]]
  spawnSync(polite[0], polite[1], { windowsHide: true, stdio: 'ignore' })
  const end = Date.now() + timeoutMs
  while (Date.now() < end) {
    if (!isRunning(exeName)) return true
    await sleep(250)
  }
  spawnSync(force[0], force[1], { windowsHide: true, stdio: 'ignore' })
  for (let i = 0; i < 20 && isRunning(exeName); i++) await sleep(250)
  return !isRunning(exeName)
}
